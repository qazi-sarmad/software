import { describe, expect, it } from 'vitest';
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';

/**
 * WP7: docs/UI-INVENTORY.md is the single source of truth for the parallel UI redesign, so it must
 * not silently drift. This guard fails when
 *   (1) an Appendix A screen id has no entry in the inventory, or
 *   (2) the inventory no longer carries the four load-bearing fields (purpose, data functions,
 *       testids, tutorial key) for a screen, or
 *   (3) an RPC that a data module calls is absent from the RPC catalogue.
 *
 * The inventory is generated by scripts/gen-ui-inventory.mjs; regenerate it and re-run this guard
 * whenever the contract or a data module changes.
 */

const ROOT = resolve(process.cwd());
const inventory = readFileSync(resolve(ROOT, 'docs/UI-INVENTORY.md'), 'utf8');

// Appendix A, less the four retired AI ids (SA-06, OA-06, OA-07, WK-07).
const RETIRED = new Set(['SA-06', 'OA-06', 'OA-07', 'WK-07']);
const APPENDIX_A = [
  'GL-01', 'TUT-01',
  ...Array.from({ length: 15 }, (_, i) => `SA-${String(i + 1).padStart(2, '0')}`),
  ...Array.from({ length: 24 }, (_, i) => `OA-${String(i + 1).padStart(2, '0')}`),
  ...Array.from({ length: 11 }, (_, i) => `WK-${String(i + 1).padStart(2, '0')}`),
  ...Array.from({ length: 4 }, (_, i) => `EX-${String(i + 1).padStart(2, '0')}`),
].filter((id) => !RETIRED.has(id));

// Appendix B: the core audit workspace, auth and chrome the Appendix A ids never covered.
const APPENDIX_B = [
  'DB-01', 'WQ-01',
  'AU-01', 'AU-02',
  ...Array.from({ length: 5 }, (_, i) => `AP-${String(i + 1).padStart(2, '0')}`),
  ...Array.from({ length: 3 }, (_, i) => `SR-${String(i + 1).padStart(2, '0')}`),
  ...Array.from({ length: 14 }, (_, i) => `AF-${String(i + 1).padStart(2, '0')}`),
  ...Array.from({ length: 5 }, (_, i) => `IR-${String(i + 1).padStart(2, '0')}`),
  'AX-01', 'AX-02',
  ...Array.from({ length: 6 }, (_, i) => `CH-${String(i + 1).padStart(2, '0')}`),
  'SA-16', 'OA-25', 'OA-26', 'OA-27', 'OA-28',
];

/** Screen ids named in the inventory's section headers. */
function documentedIds(): Set<string> {
  const out = new Set<string>();
  for (const m of inventory.matchAll(/^### (.+)$/gm)) {
    for (const id of m[1].match(/[A-Z]{2,3}-\d{2}/g) ?? []) out.add(id);
  }
  return out;
}

describe('UI inventory covers every Appendix A screen (WP7)', () => {
  it('every Appendix A id has an entry', () => {
    const documented = documentedIds();
    const missing = APPENDIX_A.filter((id) => !documented.has(id));
    expect(missing, `missing from docs/UI-INVENTORY.md: ${missing.join(', ')}`).toEqual([]);
  });

  it('every Appendix B id has an entry', () => {
    const documented = documentedIds();
    const missing = APPENDIX_B.filter((id) => !documented.has(id));
    expect(missing, `missing from docs/UI-INVENTORY.md: ${missing.join(', ')}`).toEqual([]);
  });

  it('the inventory documents the four load-bearing fields', () => {
    for (const field of [
      '- **Purpose:**',
      '- **Data functions',
      '- **Testids',
      '- **Tutorial key:**',
      '- **Rights required:**',
      '- **States:**',
      // E10: the explain layer, the standards and the drilldown targets are part of the inventory's
      // contract with the redesign, so their absence is drift, not a formatting choice.
      '- **Explain ids',
      '- **IIA standards addressed',
      '- **Drilldown targets',
    ]) {
      expect(inventory, `field ${field} absent`).toContain(field);
    }
  });

  it('the RPC catalogue names every RPC a data module calls', async () => {
    const { readdirSync } = await import('node:fs');
    const dir = resolve(ROOT, 'src/data');
    const rpcs = new Set<string>();
    for (const f of readdirSync(dir).filter((n) => n.endsWith('.ts') && !n.endsWith('.test.ts'))) {
      const s = readFileSync(resolve(dir, f), 'utf8');
      for (const m of s.matchAll(/rpc\('([a-z_0-9]+)'/g)) rpcs.add(m[1]);
    }
    const catalogue = inventory.slice(inventory.indexOf('## RPC catalogue'));
    const missing = [...rpcs].filter((r) => !catalogue.includes('`' + r + '`')).sort();
    expect(missing, `RPCs absent from the catalogue: ${missing.join(', ')}`).toEqual([]);
  });

  // E10 defect fix: nothing ran the generator, so a drift in the derived fields (explain ids,
  // standards, drilldown targets) could sit in CI unseen. This regenerates into a temp file and
  // requires it to equal the committed doc byte-for-byte — the only check that catches a stale
  // derived field. It runs the same `npx tsx` invocation the doc tells a reader to use.
  it('the committed inventory is exactly what the generator produces', () => {
    const dir = mkdtempSync(join(tmpdir(), 'ui-inventory-'));
    const out = join(dir, 'UI-INVENTORY.md');
    try {
      execFileSync('npx', ['tsx', 'scripts/gen-ui-inventory.mjs', out], { cwd: ROOT, stdio: 'pipe' });
      const generated = readFileSync(out, 'utf8');
      expect(
        generated,
        'docs/UI-INVENTORY.md is stale — run `npx tsx scripts/gen-ui-inventory.mjs` and commit the result'
      ).toBe(inventory);
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });
});
